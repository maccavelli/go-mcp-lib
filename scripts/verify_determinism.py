"""Stage-4 determinism verification.

Regenerates the protocol package twice from identical inputs into two
different scratch directories (differing names, shuffled conditions) and
asserts byte-identical outputs, unchanged mtimes on a second run, and no
timestamps, machine paths, account names, or network requests in outputs.
"""

import filecmp
import os
import shutil
import subprocess
import sys
import tempfile

# Repository root: the directory containing this script's parent.
SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLI = "/tmp/mcpgen-cli"


def build_scratch(dst):
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    for path in ("schema/inputs/2026-07-28/schema.json",):
        s, d = os.path.join(SRC, path), os.path.join(dst, path)
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copy2(s, d)


def published_files(dst):
    return sorted(
        f for f in os.listdir(os.path.join(dst, "protocol"))
        if f.endswith(".go") or f == "generated-manifest.json"
    )


def main():
    failures = []

    def check(name, ok, detail=""):
        print(("pass " if ok else "FAIL ") + name + (f": {detail}" if detail else ""))
        if not ok:
            failures.append(name)

    first = tempfile.mkdtemp(prefix="mcpgen-det-a-")
    second = tempfile.mkdtemp(prefix="mcpgen-det-b-")
    try:
        build_scratch(first)
        build_scratch(second)

        r1 = subprocess.run([CLI, "generate", "--repo", first], capture_output=True, text=True)
        check("first generate", r1.returncode == 0, r1.stderr.strip()[-100:])
        r2 = subprocess.run([CLI, "generate", "--repo", second], capture_output=True, text=True)
        check("second generate", r2.returncode == 0, r2.stderr.strip()[-100:])

        names1 = published_files(first)
        names2 = published_files(second)
        check("same inventory", names1 == names2, f"{names1} vs {names2}")

        for name in names1:
            a = os.path.join(first, "protocol", name)
            b = os.path.join(second, "protocol", name)
            if not filecmp.cmp(a, b, shallow=False):
                check(f"byte-identical {name}", False)
            else:
                check(f"byte-identical {name}", True)

        # Determinism leaks: no absolute paths, no account names, no
        # timestamps in generated bytes. The scan strings are derived at
        # runtime from the local environment, never hardcoded identifiers.
        home = os.path.expanduser("~")
        account = os.environ.get("USER", "")
        for name in names1:
            body = open(os.path.join(first, "protocol", name)).read()
            leaked = (
                SRC in body
                or home in body
                or (account and account in body)
                or "/Users/" in body
            )
            check(f"no identity leaks in {name}", not leaked)

        # Mtime preservation: regenerate over a clean tree and confirm
        # unchanged files keep their modification times.
        before = {
            name: os.path.getmtime(os.path.join(first, "protocol", name))
            for name in names1
        }
        r3 = subprocess.run([CLI, "generate", "--repo", first], capture_output=True, text=True)
        check("third generate over clean tree", r3.returncode == 0, r3.stderr.strip()[-100:])
        changed = [
            name for name, t in before.items()
            if os.path.getmtime(os.path.join(first, "protocol", name)) != t
        ]
        check("mtimes preserved on regeneration", not changed, f"changed: {changed}")
    finally:
        shutil.rmtree(first, ignore_errors=True)
        shutil.rmtree(second, ignore_errors=True)

    print(f"determinism verification: {len(failures)} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
