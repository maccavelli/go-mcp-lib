#!/usr/bin/env python3
"""Local gates: explicit preparation, fresh tests, lint and honest readiness."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile

from gate_common import linter, lint_module, precheck, report, revive, run, selected_modules, test_module

ROOT = Path(os.environ.get("GO_MCP_GATE_ROOT", Path(__file__).resolve().parent.parent)).resolve()
MODULE_CHECKS = {"fmt-check": frozenset({"fmt"}), "lint": frozenset({"lint"}),
                 "vet": frozenset({"vet"}), "test": frozenset({"vet", "test"})}
MODES = ("setup", "pre-add", "unit", "generate-check", "api", "wire", "qualification", "plants", "inventory", *MODULE_CHECKS)

PLANT_SOURCE = '''// Package plant exercises the actual deprecation analyzer.
package plant

import "github.com/modelcontextprotocol/go-sdk/mcp"

// Deprecated exercises a forbidden upstream binding.
func Deprecated() any { return new(mcp.CreateMessageResult) }
'''


def mode_plants(root: Path, pins: dict) -> int:
    executable, errors = linter(root, pins)
    failures = report("plants.linter", errors)
    if errors:
        return failures
    for generated in (False, True):
        name = "generated" if generated else "handwritten"
        with tempfile.TemporaryDirectory(prefix="mcp-lint-plant-") as temporary:
            scratch = Path(temporary)
            for filename in ("go.mod", "go.sum"):
                shutil.copy2(root / filename, scratch / filename)
            source = scratch / "plant.go"
            header = "// Code generated by mcpgen; DO NOT EDIT.\n\n" if generated else ""
            source.write_text(header + "// Package plant supplies a valid analyzer control.\npackage plant\n\n// Valid returns the control value.\nfunc Valid() int { return 1 }\n")
            command = [executable, "run", "--config", str(root / ".golangci.yml")]
            control = run(command, scratch)
            failures += report(f"plants.{name}.control", [control.stdout + control.stderr] if control.returncode else [])
            source.write_text(header + PLANT_SOURCE)
            broken = run(command, scratch)
            output = broken.stdout + broken.stderr
            caught = broken.returncode != 0 and "SA1019" in output
            failures += report(f"plants.{name}.deprecated", [] if caught else [f"SA1019 not observed: {output}"], "SA1019 caught")
            # Compare the former duplicate producer with the canonical owner.
            for valid in (True, False):
                argument = "1" if valid else '"wrong"'
                source.write_text(header + '// Package plant exercises printf analysis.\npackage plant\nimport "fmt"\n// Print exercises printf argument analysis.\nfunc Print() { fmt.Printf("%d", ' + argument + ') }\n')
                for owner, args in (("vet", ["go", "vet", "./..."]),
                                    ("govet", [executable, "run", "--config", str(root / ".golangci.yml"), "--enable-only", "govet"])):
                    result = run(args, scratch)
                    output = result.stdout + result.stderr
                    expected = result.returncode == 0 if valid else result.returncode != 0 and "Printf" in output
                    failures += report(f"plants.{name}.{owner}.{'valid' if valid else 'broken'}",
                                       [] if expected else [f"unexpected analyzer result: {output}"],
                                       "valid control passed" if valid else "printf mismatch caught")
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=MODES)
    parser.add_argument("--module", choices=("runtime", "generator", "all"), default="all")
    parser.add_argument("--allow-network", action="store_true")
    args = parser.parse_args(argv)
    if args.allow_network and args.mode != "setup":
        parser.error("--allow-network is only valid for setup")
    if args.module != "all" and args.mode not in {"unit", "pre-add", *MODULE_CHECKS}:
        parser.error("--module selection is only valid for module checks")
    try:
        pins = json.loads((ROOT / "tools/versions.json").read_text())
        if args.mode == "setup":
            from prepare import prepare
            failures = prepare(ROOT, pins, args.allow_network)
        elif args.mode == "pre-add":
            failures = precheck(ROOT, args.module, pins)
        elif args.mode in MODULE_CHECKS:
            failures = precheck(ROOT, args.module, pins, MODULE_CHECKS[args.mode])
        elif args.mode == "unit":
            executable, errors = linter(ROOT, pins)
            documentation, doc_errors = revive(ROOT, pins)
            errors += doc_errors
            failures = report("unit.linter", errors)
            for name, relative in selected_modules(args.module):
                failures += test_module(ROOT / relative, name)
                if errors:
                    failures += report(f"lint.{name}", ["pinned linter unavailable"])
                else:
                    failures += lint_module(ROOT, ROOT / relative, name, executable, documentation)
        elif args.mode == "plants":
            failures = mode_plants(ROOT, pins)
        elif args.mode == "inventory":
            from acceptance_inventory import check_inventory
            failures = check_inventory(ROOT, pins)
        else:
            owners = {"generate-check": "R2/R3 complete generator candidate contract",
                      "api": "R2/R5 generated and external-consumer API contract",
                      "wire": "Stage 7 guarded transports",
                      "qualification": "Stage 9 complete product matrix"}
            failures = report(args.mode, [f"incomplete: {owners[args.mode]}"])
    except (OSError, ValueError, KeyError, TypeError) as exc:
        failures = report(args.mode, [f"invalid or unavailable input: {exc}"])
    print(f"gate {args.mode}: {failures} FAIL case(s)" if failures else f"gate {args.mode}: all cases pass")
    return int(bool(failures))


if __name__ == "__main__":
    sys.exit(main())
