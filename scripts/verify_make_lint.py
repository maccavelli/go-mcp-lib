"""Prove actual Make lint rejects each documentation rule, also in generated Go."""

import json
from pathlib import Path
import shutil
import subprocess
import tempfile

from gate_common import environment, linter, report, revive

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    pins = json.loads((ROOT / "tools/versions.json").read_text())
    executable, errors = linter(ROOT, pins)
    documentation, doc_errors = revive(ROOT, pins)
    errors += doc_errors
    failures = report("make-lint.tool", errors)
    make = shutil.which("make")
    if errors or not make:
        return failures + report("make-lint.make", [] if make else ["Make tool unavailable"])
    for generated in (False, True):
        prefix = "// Code generated by mcpgen; DO NOT EDIT.\n\n" if generated else ""
        with tempfile.TemporaryDirectory(prefix="mcp-make-lint-") as directory:
            root = Path(directory)
            (root / "scripts").mkdir()
            (root / "tools").mkdir()
            for name in ("Makefile", ".golangci.yml", ".revive.toml", "go.mod", "go.sum", "tools/versions.json", "tools/documentation-lint.json",
                         "scripts/make_tasks.py", "scripts/gate.py", "scripts/gate_common.py"):
                shutil.copy2(ROOT / name, root / name)
            (root / "input.txt").write_text("fixture")
            ordinary = '// Package plant supplies a documentation control.\npackage plant\nvar requestID = 1\n// Read returns the fixture identifier.\nfunc Read() int { return requestID }\n'
            embedded = '// Package plant supplies an import control.\npackage plant\nimport _ "net/http/pprof" // Registers the diagnostic handlers.\n// Read returns the fixture value.\nfunc Read() int { return 1 }\n'
            cases = {
                "exported": (ordinary, ordinary.replace("// Read returns the fixture identifier.\n", "")),
                "package-comments": (ordinary, ordinary.replace("// Package plant supplies a documentation control.\n", "")),
                "var-naming": (ordinary, ordinary.replace("requestID", "requestId")),
                "blank-imports": (embedded, embedded.replace(" // Registers the diagnostic handlers.", "")),
            }
            env = environment()
            env["GO_MCP_LINTER"] = executable
            env["GO_MCP_REVIVE"] = documentation
            for name, (valid, broken) in cases.items():
                for control, body in ((True, valid), (False, broken)):
                    (root / "plant.go").write_text(prefix + body)
                    result = subprocess.run([make, "lint", "MODULE=runtime", "PYTHON=" + shutil.which("python3")], cwd=root,
                                            env=env, capture_output=True, text=True, check=False, timeout=120)
                    output = result.stdout + result.stderr
                    caught = result.returncode == 0 if control else result.returncode != 0 and name in output
                    case = f"make-lint.{'generated' if generated else 'handwritten'}.{name}.{'control' if control else 'plant'}"
                    failures += report(case, [] if caught else [f"exit {result.returncode}: {output}"],
                                       "valid input passed" if control else f"FAIL {name} caught through make lint")
    return int(bool(failures))


if __name__ == "__main__":
    raise SystemExit(main())
